const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs/promises');

(async () => {
  const root = path.resolve(__dirname, '..');
  await fs.mkdir(path.join(root, 'artifacts'), { recursive: true });
  const env = { ...process.env, STUDIO_USER_DATA: path.join(root, '.review-data', `desktop-smoke-${Date.now()}`), STUDIO_TOOLCHAIN_ROOT: path.join(root, '.tools') };
  delete env.ELECTRON_RUN_AS_NODE; delete env.STUDIO_DEV_URL;
  let app;
  const errors = [];
  try {
    const launchOptions = process.env.STUDIO_PACKAGED_EXE ? { executablePath: process.env.STUDIO_PACKAGED_EXE, args: [], env } : { args: [root], env };
    app = await electron.launch(launchOptions);
    const page = await app.firstWindow();
    page.on('pageerror', e => errors.push(e.message));
    await page.getByRole('heading', { name: '條件與分支.' }).waitFor();
    await page.locator('.monaco-editor').waitFor();
    await page.waitForTimeout(1000);
    assert.equal(await page.locator('#language-select option').count(), 6);
    assert.equal(await page.locator('.topic-link').count(), 21);
    assert.equal(await page.getByText('綜合挑戰', { exact: true }).count(), 0);
    await page.screenshot({ path: path.join(root, 'artifacts', '01-workbench.png') });
    await page.getByLabel('程式語言', { exact: true }).selectOption('javascript');
    await page.getByRole('button', { name: '查看參考解答' }).click();
    await page.getByRole('button', { name: '載入編輯器' }).click();
    await page.getByRole('button', { name: '提交驗證', exact: true }).click();
    await page.locator('.test-summary.success').waitFor({ timeout: 30000 });
    assert.equal(await page.locator('.test-row.pass').count(), 4);
    await page.screenshot({ path: path.join(root, 'artifacts', '02-tests-passed.png') });
    await page.getByRole('button', { name: '執行程式', exact: false }).first().click();
    await page.getByText('執行完成', { exact: true }).waitFor();
    assert.match(await page.locator('.output-block').innerText(), /0/);
    await page.getByLabel('程式語言', { exact: true }).selectOption('haskell');
    await page.getByRole('button', { name: '語言比較' }).click();
    assert.equal(await page.locator('.comparison-list article').count(), 6);
    await page.screenshot({ path: path.join(root, 'artifacts', '03-comparison.png') });
    await page.getByRole('button', { name: '概念教學', exact: true }).click();
    await page.getByRole('button', { name: '本題練習', exact: true }).click();
    await page.getByRole('heading', { name: '幫售票員算出票價', exact: true }).waitFor();
    await page.getByLabel('搜尋課程主題').fill('泛型');
    assert.equal(await page.locator('.topic-link').count(), 1);
    await page.locator('.topic-link').click();
    await page.getByRole('heading', { name: '泛型與型別參數.' }).waitFor();
    await page.getByRole('button', { name: '開始本題練習' }).click();
    await page.getByRole('heading', { name: '泛型的首值或預設值', exact: true }).waitFor();
    await page.getByRole('button', { name: '查看參考解答' }).click();
    await page.getByRole('button', { name: '載入編輯器' }).click();
    await page.getByRole('button', { name: '提交驗證', exact: true }).click();
    await page.locator('.test-summary.success').waitFor({ timeout: 30000 });
    await page.getByLabel('搜尋課程主題').fill('');
    assert.equal(await page.locator('.topic-link').count(), 21);
    await page.screenshot({ path: path.join(root, 'artifacts', '06-topic-practice.png') });
    assert.equal((await fs.readdir(root)).some(name => name.endsWith('.cmd')), false);
    await page.getByRole('button', { name: '學習總覽', exact: true }).click();
    assert.equal(await page.locator('.language-card').count(), 6);
    await page.screenshot({ path: path.join(root, 'artifacts', '04-overview.png') });
    await page.getByRole('button', { name: '環境與設定', exact: true }).click();
    await page.getByRole('heading', { name: 'ChatGPT 帳戶', exact: true }).waitFor();
    await page.getByText('正在檢查帳戶…', { exact: true }).waitFor({ state: 'hidden', timeout: 35000 });
    await page.screenshot({ path: path.join(root, 'artifacts', '05-settings.png') });
    const state = await page.evaluate(() => window.studio.load());
    assert.ok(state.completed.includes('javascript:branches'));
    assert.ok(state.drafts['javascript:branches'].includes('if (age < 6)'));
    assert.equal(state.selectedLanguage, 'haskell');
    const account = await page.evaluate(() => window.studio.authStatus());
    assert.equal(typeof account.available, 'boolean');
    assert.equal(account.loggedIn, false);
    const noLogin = await page.evaluate(async () => { try { await window.studio.review({ language: 'JavaScript', topic: '條件', task: '判斷票價', code: 'console.log(0)', results: '尚未測試' }); return ''; } catch (error) { return error.message; } });
    assert.match(noLogin, /帳戶/);
    assert.equal(errors.length, 0, errors.join('\n'));
    await app.close();
    app = await electron.launch(launchOptions);
    const reopened = await app.firstWindow();
    await reopened.waitForFunction(() => document.querySelector('#language-select')?.value === 'haskell');
    const restored = await reopened.evaluate(() => window.studio.load());
    assert.deepEqual(restored, state);
    await reopened.locator('.monaco-editor[data-ready-language="haskell"]').waitFor();
    await reopened.locator('.monaco-editor .view-lines').click({ position: { x: 50, y: 20 } });
    await reopened.keyboard.press('Control+End');
    await reopened.keyboard.insertText('\n-- close-save-check');
    await reopened.waitForFunction(() => document.querySelector('.monaco-editor .view-lines')?.textContent.includes('close-save-check'));
    const closed = app.waitForEvent('close');
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close());
    await closed;
    app = await electron.launch(launchOptions);
    const finalWindow = await app.firstWindow();
    await finalWindow.waitForFunction(() => document.querySelector('#language-select')?.value === 'haskell');
    const immediatelySaved = await finalWindow.evaluate(() => window.studio.load());
    assert.match(immediatelySaved.drafts['haskell:generics'], /close-save-check/);
    console.log(JSON.stringify({ result: 'PASS', completed: state.completed, rendererErrors: errors, screenshots: 6 }, null, 2));
  } catch (error) {
    if (app) await app.firstWindow().then(page => page.screenshot({ path: path.join(root, 'artifacts', 'error-desktop.png') })).catch(() => {});
    throw error;
  } finally {
    if (app) { const timer = setTimeout(() => app.process().kill(), 5000); await app.close().catch(() => {}); clearTimeout(timer); }
  }
})().catch(e => { console.error(e); process.exitCode = 1; });
